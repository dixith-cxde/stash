// Converts the Material Symbols vector drawables in assets/icons (from
// `npx @expo/material-symbols --style rounded -o assets/icons <name>`) into SVG path data
// for react-native-svg. Run with `npm run icons` after adding an icon.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'assets/icons';
const camel = (file) => {
  const base = file.replace(/\.xml$/, '');
  const fill = base.endsWith('_rounded_fill');
  const name = base.replace(/_rounded(_fill)?$/, '').replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
  return fill ? `${name}Fill` : name;
};

const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.xml'))
  .sort()
  .map((file) => {
    const xml = readFileSync(join(dir, file), 'utf8');
    const viewport = Number(/android:viewportWidth="([\d.]+)"/.exec(xml)?.[1]);
    if (viewport !== 960) throw new Error(`${file}: expected a 960 viewport, got ${viewport}`);
    const paths = [...xml.matchAll(/android:pathData="([^"]+)"/g)].map((m) => m[1]);
    if (!paths.length) throw new Error(`${file}: no pathData`);
    return `  ${camel(file)}: '${paths.join(' ')}',`;
  });

writeFileSync(
  'src/theme/iconPaths.ts',
  `/* Generated by scripts/build-icons.mjs from assets/icons. Do not edit. Viewbox 0 0 960 960. */\n` +
    `export const IconPaths = {\n${entries.join('\n')}\n} as const;\n`,
);
console.log(`Wrote ${entries.length} icons to src/theme/iconPaths.ts`);

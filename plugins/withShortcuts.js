// Launcher shortcuts: long-press the Stash icon → Paste link / New note / Upload file.
// Static shortcuts (res/xml/stash_shortcuts.xml on MainActivity) open the same stash://capture
// deep links as the home-screen widget's Note and File buttons. Labels and icons live in
// modules/expressive (res/values/stash_widget_strings.xml, res/drawable-anydpi-v26).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const FILE = 'stash_shortcuts';

const SHORTCUTS = [
  { id: 'paste', query: 'paste=1', label: 'stash_shortcut_paste', icon: 'stash_shortcut_paste' },
  { id: 'note', query: 'mode=note', label: 'stash_shortcut_note', icon: 'stash_shortcut_note' },
  { id: 'file', query: 'mode=file', label: 'stash_shortcut_file', icon: 'stash_shortcut_file' },
];

function shortcutsXml(pkg) {
  const items = SHORTCUTS.map(
    (s) => `  <shortcut
    android:shortcutId="${s.id}"
    android:enabled="true"
    android:icon="@drawable/${s.icon}"
    android:shortcutShortLabel="@string/${s.label}"
    android:shortcutLongLabel="@string/${s.label}">
    <intent
      android:action="android.intent.action.VIEW"
      android:data="stash://capture?${s.query}"
      android:targetPackage="${pkg}"
      android:targetClass="${pkg}.MainActivity" />
  </shortcut>`,
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withShortcuts.js -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${items}
</shortcuts>
`;
}

module.exports = function withShortcuts(config) {
  config = withAndroidManifest(config, (cfg) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    const meta = (activity['meta-data'] ?? []).filter((m) => m.$['android:name'] !== 'android.app.shortcuts');
    meta.push({ $: { 'android:name': 'android.app.shortcuts', 'android:resource': `@xml/${FILE}` } });
    activity['meta-data'] = meta;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('withShortcuts: android.package is not set in app.json');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${FILE}.xml`), shortcutsXml(pkg));
      return cfg;
    },
  ]);
};
